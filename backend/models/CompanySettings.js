const mongoose = require('mongoose');
const auditPlugin = require('./plugins/auditPlugin');
const cacheInvalidationPlugin = require('./plugins/cacheInvalidationPlugin');
const redisKeys = require('../utils/redisKeys');
const { ADDRESS_LINE_MAX_LENGTH, POSTAL_CODE_MAX_LENGTH, TAX_FIELD_VALUE_MAX_LENGTH } = require('../constants/taxConstants');
const { SHORT_NAME_PLACES, SHORT_NAME_PLACE_VALUES } = require('../constants/jobOrderConstants');
const { WORK_TIME_STARTS, WORK_TIME_START_VALUES } = require('../constants/stepConstants');

// The business in one of the vendor's countries (CompanyMaster.assignedCountries):
// its address there and its tax registration. Company Settings > Tax.
const taxDetailSchema = new mongoose.Schema({
    countryId: {
        type: mongoose.Types.ObjectId,
        ref: 'CountryMaster',
        required: true
    },
    // State / city from StateMaster / CityMaster of this country.
    address: {
        line1: { type: String, trim: true, maxlength: ADDRESS_LINE_MAX_LENGTH, default: null },
        line2: { type: String, trim: true, maxlength: ADDRESS_LINE_MAX_LENGTH, default: null },
        stateId: { type: mongoose.Types.ObjectId, ref: 'StateMaster', default: null },
        cityId: { type: mongoose.Types.ObjectId, ref: 'CityMaster', default: null },
        postalCode: { type: String, trim: true, maxlength: POSTAL_CODE_MAX_LENGTH, default: null }
    },
    // "I am registered for GST / VAT here". Only then is tax charged on job
    // orders of this country - and the address and the country's required
    // tax fields must be filled.
    isTaxRegistered: {
        type: Boolean,
        default: false
    },
    // The country's tax fields (CountryMaster.taxFields), by key - e.g.
    // { gstin: '27ABCDE1234F1Z5', pan: 'ABCDE1234F' }.
    taxFieldValues: {
        type: Map,
        of: { type: String, maxlength: TAX_FIELD_VALUE_MAX_LENGTH },
        default: {}
    },
    // The rate picked in advance on a new job order (a TaxMaster of this
    // country); null = the platform's default rate for the country. The
    // owner can still pick another one on the job order.
    defaultTaxId: {
        type: mongoose.Types.ObjectId,
        ref: 'TaxMaster',
        default: null
    }
}, { _id: false });

// The vendor's own settings, set by the vendor - company name, logo, what the
// login page says, etc. Cached in Redis with the other vendor data
// (ensureVendorDataCached), so reading it costs no DB query.
const companySettingsSchema = new mongoose.Schema({
    vendorId: {
        type: mongoose.Types.ObjectId,
        required: true,
        unique: true
    },
    // Shown on the login page, in the sidebar and as the browser tab title.
    companyName: {
        type: String,
        required: true,
        trim: true,
        minlength: 2,
        maxlength: 100
    },
    // Optional line under the company name on the login page.
    loginTagline: {
        type: String,
        trim: true,
        maxlength: 150,
        default: null
    },
    // The current logo. url is kept here so showing the logo needs no extra
    // query; imageId is its ImageAsset, needed to replace or delete the file.
    logo: {
        url: { type: String, default: null },
        imageId: { type: mongoose.Types.ObjectId, ref: 'ImageAsset', default: null }
    },
    // ---- Job orders (Company Settings > General) ---------------------------
    // The app numbers job orders itself (JO-0001, JO-0002...); off = the
    // owner types the number on each job order.
    isJobOrderNumberAutoGenerated: {
        type: Boolean,
        default: true
    },
    // The job order asks for the customer's country, state, city, postal code
    // and address (none of them required).
    askCustomerAddress: {
        type: Boolean,
        default: true
    },
    // Where a master shows its short name instead of its name (a master with
    // no short name keeps its name): nowhere, the job order page, print, both.
    useShortNamesOn: {
        type: String,
        enum: SHORT_NAME_PLACE_VALUES,
        default: SHORT_NAME_PLACES.NOWHERE
    },
    // When the completion time of assigned work starts: when the work is
    // given, or when each person changes their first step (only while the
    // steps feature is on; otherwise always when given).
    workTimeStartsOn: {
        type: String,
        enum: WORK_TIME_START_VALUES,
        default: WORK_TIME_STARTS.ON_ASSIGN
    },
    // One per country the vendor has filled in (Company Settings > Tax).
    // Entries of a country no longer assigned are kept, and used again if it
    // is given back.
    taxDetails: {
        type: [taxDetailSchema],
        default: []
    }
}, {
  timestamps: true
});

companySettingsSchema.plugin(auditPlugin);
companySettingsSchema.plugin(cacheInvalidationPlugin, { key: (vendorId) => redisKeys.companySettings(vendorId) });

module.exports = mongoose.model('CompanySettings', companySettingsSchema);
