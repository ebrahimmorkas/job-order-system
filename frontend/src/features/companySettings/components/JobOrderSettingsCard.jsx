import { useEffect, useState } from 'react';
import Button from '../../../components/common/Buttons';
import Card from '../../../components/common/Card';
import Checkbox from '../../../components/common/Checkbox';
import { Radio } from '../../../components/common/Radio';
import Alert from '../../../components/common/Alert';
import { useToast } from '../../../components/common/Toast';
import * as companySettingsApi from '../api/companySettingsApi';

// Same values as the backend (constants/jobOrderConstants.js SHORT_NAME_PLACES).
const SHORT_NAME_CHOICES = [
  { value: 'none', label: 'Nowhere', description: 'Full master names everywhere.' },
  { value: 'jobOrder', label: 'Job order page', description: 'Short names on the job order form.' },
  { value: 'print', label: 'Print', description: 'Short names on the printed job order.' },
  { value: 'both', label: 'Both', description: 'Short names on the form and on the print.' },
];

// Same values as the backend (constants/jobOrderConstants.js PRICE_CALCULATIONS).
const PRICE_CHOICES = [
  { value: 'manual', label: 'I enter the price', description: 'You work out the price for all the pieces and type it on the job order.' },
  { value: 'rateTimesQuantity', label: 'Software calculates the price', description: 'You type the rate of one piece; the price is rate × quantity (the quantity field of Controls). You can still change the price by hand.' },
];

// Same values as the backend (constants/pricingConstants.js CHARGE_BY).
const CHARGE_CHOICES = [
  { value: 'piece', label: 'Per piece', description: 'One price per piece, e.g. a mattress cut for ₹500.' },
  { value: 'unit', label: 'Per unit (meter, sq ft...)', description: 'A rate per unit of size, e.g. ₹100 per meter or per sq ft. The job order asks the size.' },
];

// Same values as the backend (constants/pricingConstants.js ROUND_TOTAL_STEPS / DIRECTIONS).
const ROUND_STEPS = [
  { value: '', label: 'Don\'t round' },
  { value: '1', label: 'To 1' },
  { value: '5', label: 'To 5' },
  { value: '10', label: 'To 10' },
];
const ROUND_DIRECTIONS = [
  { value: 'nearest', label: 'Nearest', description: '1,234.40 -> 1,234 · 1,234.60 -> 1,235' },
  { value: 'up', label: 'Always up', description: '1,234.10 -> 1,235' },
  { value: 'down', label: 'Always down', description: '1,234.90 -> 1,234' },
];

// Same values as the backend (constants/stepConstants.js WORK_TIME_STARTS).
const WORK_TIME_CHOICES = [
  { value: 'onAssign', label: 'When the work is given', description: 'As soon as the job order is created (or the work is given on an edit).' },
  { value: 'onFirstStep', label: 'When the person starts', description: 'From the first step each person moves their work to - everyone has their own time.' },
];

// Same values as the backend (constants/stepConstants.js WORK_TIME_CHANGE_FROM).
const TIME_CHANGE_CHOICES = [
  { value: 'personStart', label: 'From the day they started', description: 'Started Monday with 3 days, changed on Tuesday to 5 days: due Saturday.' },
  { value: 'change', label: 'From the moment you change it', description: 'Started Monday with 3 days, changed on Tuesday to 5 days: due Sunday.' },
];

// What the "Work given" field of a print layout shows (backend
// constants/jobOrderConstants.js PRINT_WORK_OPTIONS); step options need steps on.
const PRINT_WORK_CHOICES = [
  { key: 'showWorkers', label: 'Who does it' },
  { key: 'showStartDate', label: 'Start date' },
  { key: 'showDueTime', label: 'Due time' },
  { key: 'showStep', label: 'Step and %', needsSteps: true },
  { key: 'showHoldReason', label: 'Hold reason', needsSteps: true },
];

const sameSettings = (a, b) =>
  a.isJobOrderNumberAutoGenerated === b.isJobOrderNumberAutoGenerated && a.askCustomerAddress === b.askCustomerAddress
  && a.useShortNamesOn === b.useShortNamesOn && a.workTimeStartsOn === b.workTimeStartsOn
  && a.workTimeChangeCountsFrom === b.workTimeChangeCountsFrom && a.priceCalculation === b.priceCalculation
  && a.chargeBy === b.chargeBy && (a.roundTotalTo ?? null) === (b.roundTotalTo ?? null) && a.roundTotalDirection === b.roundTotalDirection
  && a.askDeliveryDate === b.askDeliveryDate && a.allowDiscount === b.allowDiscount && a.askAdvance === b.askAdvance
  && PRINT_WORK_CHOICES.every(({ key }) => a.printWork?.[key] === b.printWork?.[key]);

/**
 * Company Settings > General > Job orders: how the job order number is made,
 * whether the customer's address is asked, where masters show their short
 * names, how prices are worked out (typed, or rate × quantity), how items
 * are charged (per piece / per unit, with per unit pricing), the delivery
 * date, discount and advance asked, how the total is rounded off and (with
 * the steps feature) when the time of assigned work starts -
 * and, when it starts at each person's first step, what a changed time of
 * work someone already started counts from - and what the printed "Work
 * given" field shows.
 *
 * @param {Object} props
 * @param {{ isJobOrderNumberAutoGenerated: boolean, askCustomerAddress: boolean, useShortNamesOn: string, workTimeStartsOn: string, workTimeChangeCountsFrom: string }} props.initial
 * @param {(key: string, isDirty: boolean) => void} props.onDirtyChange
 * @param {boolean} [props.showWorkTime] - The steps feature is on
 * @param {boolean} [props.showPrintWork] - Layout Master and RBAC are on
 * @param {boolean} [props.showPerRate] - Per unit pricing is on
 */
const JobOrderSettingsCard = ({ initial, onDirtyChange, showWorkTime = false, showPrintWork = false, showPerRate = false }) => {
  const toast = useToast();
  const [saved, setSaved] = useState(initial);
  const [fields, setFields] = useState(initial);
  const [error, setError] = useState('');
  const [isSaving, setIsSaving] = useState(false);

  const isDirty = !sameSettings(fields, saved);
  useEffect(() => { onDirtyChange('jobOrder', isDirty); }, [isDirty, onDirtyChange]);

  const setField = (field, value) => {
    setFields((prev) => ({ ...prev, [field]: value }));
    if (error) setError('');
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (isSaving) return;
    setIsSaving(true);
    try {
      const { jobOrder } = await companySettingsApi.updateJobOrderSettings(fields);
      setSaved(jobOrder);
      setFields(jobOrder);
      toast.success('Job order settings saved.');
    } catch (err) {
      setError(err.message);
    } finally {
      setIsSaving(false);
    }
  };

  return (
    <form onSubmit={handleSubmit} noValidate>
      <Card variant="outlined" title="Job orders" subtitle="How new job orders are filled in.">
        <div className="space-y-5">
          {error && <Alert variant="error">{error}</Alert>}
          <Checkbox
            name="isJobOrderNumberAutoGenerated"
            label="Make the job order number automatically"
            description={fields.isJobOrderNumberAutoGenerated ? 'Numbered JO-0001, JO-0002 and so on.' : 'You type the number on every job order.'}
            checked={fields.isJobOrderNumberAutoGenerated}
            onChange={(e) => setField('isJobOrderNumberAutoGenerated', e.target.checked)}
            disabled={isSaving}
          />
          <Checkbox
            name="askCustomerAddress"
            label="Ask the customer address"
            description="Country, state, city, postal code and full address on the job order (all optional). The tax depends on the customer's country and state."
            checked={fields.askCustomerAddress}
            onChange={(e) => setField('askCustomerAddress', e.target.checked)}
            disabled={isSaving}
          />
          <fieldset>
            <legend className="mb-2 text-sm font-medium text-gray-700">Use master short names on</legend>
            <div className="grid gap-3 sm:grid-cols-2">
              {SHORT_NAME_CHOICES.map((choice) => (
                <Radio
                  key={choice.value}
                  name="useShortNamesOn"
                  value={choice.value}
                  label={choice.label}
                  description={choice.description}
                  checked={fields.useShortNamesOn === choice.value}
                  onChange={() => setField('useShortNamesOn', choice.value)}
                  disabled={isSaving}
                />
              ))}
            </div>
          </fieldset>
          <fieldset>
            <legend className="mb-1 text-sm font-medium text-gray-700">Price on a job order</legend>
            <p className="mb-2 text-xs text-gray-500">For new job orders; a job order already saved keeps the way it was made.</p>
            <div className="grid gap-3 sm:grid-cols-2">
              {PRICE_CHOICES.map((choice) => (
                <Radio
                  key={choice.value}
                  name="priceCalculation"
                  value={choice.value}
                  label={choice.label}
                  description={choice.description}
                  checked={fields.priceCalculation === choice.value}
                  onChange={() => setField('priceCalculation', choice.value)}
                  disabled={isSaving}
                />
              ))}
            </div>
          </fieldset>
          {showPerRate && (
            <fieldset>
              <legend className="mb-1 text-sm font-medium text-gray-700">How you charge</legend>
              <p className="mb-2 text-xs text-gray-500">Picked for every new item; it can be changed on each item of a job order.</p>
              <div className="grid gap-3 sm:grid-cols-2">
                {CHARGE_CHOICES.map((choice) => (
                  <Radio
                    key={choice.value}
                    name="chargeBy"
                    value={choice.value}
                    label={choice.label}
                    description={choice.description}
                    checked={fields.chargeBy === choice.value}
                    onChange={() => setField('chargeBy', choice.value)}
                    disabled={isSaving}
                  />
                ))}
              </div>
            </fieldset>
          )}
          <fieldset>
            <legend className="mb-2 text-sm font-medium text-gray-700">Also ask on a job order</legend>
            <div className="grid gap-3 sm:grid-cols-3">
              <Checkbox name="askDeliveryDate" label="Delivery date" description="When the customer gets it." checked={fields.askDeliveryDate} onChange={(e) => setField('askDeliveryDate', e.target.checked)} disabled={isSaving} />
              <Checkbox name="allowDiscount" label="Discount" description="An amount or a %, taken off before tax." checked={fields.allowDiscount} onChange={(e) => setField('allowDiscount', e.target.checked)} disabled={isSaving} />
              <Checkbox name="askAdvance" label="Advance received" description="The balance due is worked out." checked={fields.askAdvance} onChange={(e) => setField('askAdvance', e.target.checked)} disabled={isSaving} />
            </div>
          </fieldset>
          <fieldset>
            <legend className="mb-1 text-sm font-medium text-gray-700">Round off the total</legend>
            <p className="mb-2 text-xs text-gray-500">Shown as "Round off" on the job order.</p>
            <div className="flex flex-wrap gap-x-5 gap-y-2">
              {ROUND_STEPS.map((step) => (
                <Radio
                  key={step.value || 'none'}
                  name="roundTotalTo"
                  value={step.value}
                  label={step.label}
                  checked={String(fields.roundTotalTo ?? '') === step.value}
                  onChange={() => setField('roundTotalTo', step.value ? Number(step.value) : null)}
                  disabled={isSaving}
                />
              ))}
            </div>
            {fields.roundTotalTo && (
              <div className="mt-3 grid gap-3 sm:grid-cols-3">
                {ROUND_DIRECTIONS.map((direction) => (
                  <Radio
                    key={direction.value}
                    name="roundTotalDirection"
                    value={direction.value}
                    label={direction.label}
                    description={fields.roundTotalTo === 1 ? direction.description : undefined}
                    checked={fields.roundTotalDirection === direction.value}
                    onChange={() => setField('roundTotalDirection', direction.value)}
                    disabled={isSaving}
                  />
                ))}
              </div>
            )}
          </fieldset>
          {showWorkTime && (
            <fieldset>
              <legend className="mb-2 text-sm font-medium text-gray-700">The completion time of given work starts</legend>
              <div className="grid gap-3 sm:grid-cols-2">
                {WORK_TIME_CHOICES.map((choice) => (
                  <Radio
                    key={choice.value}
                    name="workTimeStartsOn"
                    value={choice.value}
                    label={choice.label}
                    description={choice.description}
                    checked={fields.workTimeStartsOn === choice.value}
                    onChange={() => setField('workTimeStartsOn', choice.value)}
                    disabled={isSaving}
                  />
                ))}
              </div>
            </fieldset>
          )}
          {showWorkTime && fields.workTimeStartsOn === 'onFirstStep' && (
            <fieldset>
              <legend className="mb-1 text-sm font-medium text-gray-700">When you change the time of work someone already started, the new time counts</legend>
              <p className="mb-2 text-xs text-gray-500">People who haven't started yet always get the new time from their first step.</p>
              <div className="grid gap-3 sm:grid-cols-2">
                {TIME_CHANGE_CHOICES.map((choice) => (
                  <Radio
                    key={choice.value}
                    name="workTimeChangeCountsFrom"
                    value={choice.value}
                    label={choice.label}
                    description={choice.description}
                    checked={fields.workTimeChangeCountsFrom === choice.value}
                    onChange={() => setField('workTimeChangeCountsFrom', choice.value)}
                    disabled={isSaving}
                  />
                ))}
              </div>
            </fieldset>
          )}
          {showPrintWork && (
            <fieldset>
              <legend className="mb-1 text-sm font-medium text-gray-700">On the printed job order</legend>
              <p className="mb-2 text-xs text-gray-500">What the "Work given" field of a print layout shows for each person.</p>
              <div className="grid gap-3 sm:grid-cols-3">
                {PRINT_WORK_CHOICES.filter((choice) => showWorkTime || !choice.needsSteps).map((choice) => (
                  <Checkbox
                    key={choice.key}
                    name={`printWork.${choice.key}`}
                    label={choice.label}
                    checked={fields.printWork?.[choice.key] === true}
                    onChange={(e) => setField('printWork', { ...fields.printWork, [choice.key]: e.target.checked })}
                    disabled={isSaving}
                  />
                ))}
              </div>
            </fieldset>
          )}
          <div className="flex justify-end">
            <Button type="submit" loading={isSaving} loadingText="Saving..." disabled={!isDirty}>Save changes</Button>
          </div>
        </div>
      </Card>
    </form>
  );
};

export default JobOrderSettingsCard;
